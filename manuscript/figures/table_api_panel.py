#!/usr/bin/env python3
"""Appendix table A-B: the Addendum B API panel, one row per model.

Every number is computed from data/runs/addB-.../games.jsonl (via fig8_models.load_addb, which rebuilds
each gap from the offered price and the fixture's limit and asserts h_f, mean h, CI and by-role means
against addendum_B.json). The counts, cost, versions and providers are recomputed here and asserted
against addendum_B.json; the Wilcoxon p and its Holm adjustment are recomputed with scripts/analyze.py's
functions and seeds (200,000 sign flips each; ~10 s). A mismatch stops the script.

Writes table_api_panel.md next to this script. Stdlib only.
"""
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fig8_models as F8  # noqa: E402
from fig8_models import A, ADDB, HIGH, LOW, close, same  # noqa: E402


def fmt_h(v):
    return f"{v:+.3f}".replace("-", "\u2212")


def main():
    models, games, ref = F8.load_addb()
    rows, pv = [], {}
    for m in models:
        arm, rs, pm = m["model"], m["records"], ref["per_model"][m["model"]]
        q = pm["quality_by_scale"]
        items = len(rs)
        same(items, pm["records"], f"{arm} records")
        same(items, pm["items_planned"], f"{arm} items planned")
        valid = sum(1 for r in rs if not r["errors"] and r["action"] == "OFFER")
        refusals = sum(1 for r in rs if "REFUSAL" in r["errors"])
        think = sum(1 for r in rs if (r.get("reasoning_tokens") or 0) > 0)
        missing = sum(1 for r in rs if r["errors"] == ["INFRASTRUCTURE"])
        invalid = sum(1 for r in rs if r["errors"] and r["errors"] != ["INFRASTRUCTURE"])
        walk = sum(1 for r in rs if not r["errors"] and r["action"] == "WALKAWAY")
        for got, key in ((valid, "valid_offers"), (refusals, "refusals"), (think, "replies_with_reasoning_tokens"),
                         (missing, "missing_infrastructure"), (walk, "walkaways")):
            same(got, sum(q[sc][key] for sc in (LOW, HIGH)), f"{arm} {key}")
        same(items - missing, sum(q[sc]["replies"] for sc in (LOW, HIGH)), f"{arm} replies")
        cost = sum(r.get("cost") or 0.0 for r in rs)
        close(cost, pm["cost_reported"], f"{arm} cost")
        vals = [float(m["h"][f]) for f in sorted(m["h"])]
        p, wplus, n = A.wilcoxon_signflip_less(vals, random.Random(A.seed("addendumB-wilcoxon-HA", arm)), ref["flips"])
        close(p, pm["HA"]["p_one_sided_unadjusted"], f"{arm} p")
        same(wplus, pm["HA"]["W_plus"], f"{arm} W+")
        same(n, pm["HA"]["n_nonzero"], f"{arm} n nonzero")
        pv[arm] = p
        rows.append(dict(m=m, items=items, valid=valid, refusals=refusals, invalid=invalid, walk=walk,
                         missing=missing, think=think, cost=cost, n_nonzero=n, wplus=wplus))
    holm = A.holm(pv)
    for r in rows:
        arm = r["m"]["model"]
        close(holm[arm], ref["per_model"][arm]["HA"]["p_holm"], f"{arm} Holm p")
        r["holm"] = holm[arm]
    same(sorted(pv), ref["holm_family"], "Holm family")

    flips, boots = ref["flips"], ref["bootstrap"]
    head = ["Model", "Dated version (returned)", "Provider (returned)", "Items", "Valid offers", "Refusals",
            "Replies with reasoning tokens", "Cost (USD)", "Mean h [95% CI]", "Fixtures h_f < 0", "Holm p"]
    out = [f"<!-- Generated by manuscript/figures/table_api_panel.py from data/runs/{ADDB}/games.jsonl, "
           f"asserted against derived/{ADDB}/addendum_B.json. Do not edit by hand. -->", "",
           "| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        m = r["m"]
        p = "< 1/" + f"{flips:,}" + " (0 flips as extreme)" if r["holm"] == 0 else f"{r['holm']:.6f}"
        out.append("| " + " | ".join([
            f"`{m['model']}`", f"`{m['version']}`", m["provider"], f"{r['items']:,}", f"{r['valid']:,}",
            f"{r['refusals']}", f"{r['think']}", f"{r['cost']:.4f}",
            f"{fmt_h(m['mean_h'])} [{fmt_h(m['ci'][0])}, {fmt_h(m['ci'][1])}]",
            f"{m['below']}/{m['n']}" + (f" ({', '.join(m['zeros'])} = 0)" if m["zeros"] else ""), p]) + " |")
    tot = sum(r["cost"] for r in rows)
    out += ["",
            f"Items: first moves, 30 fixtures \u00d7 2 roles \u00d7 2 scales \u00d7 {len({g['sample'] for g in games})} "
            f"samples. Invalid replies: {sum(r['invalid'] for r in rows)}; walkaways: {sum(r['walk'] for r in rows)}; "
            f"missing (infrastructure): {sum(r['missing'] for r in rows)}. "
            f"Cost: OpenRouter `usage.cost` summed over replies; total {tot:.4f}. "
            f"p: one-sided Wilcoxon signed-rank on the h_f, {flips:,} random sign flips, Holm across the "
            f"{len(rows)} models; CI: {boots:,} bootstrap resamples of fixtures (ADDENDUM_B.md \u00a75).", ""]
    path = os.path.join(HERE, "table_api_panel.md")
    with open(path, "w") as fh:
        fh.write("\n".join(out))
    print("\n".join(out))
    print("all table numbers match addendum_B.json")
    print(path)


if __name__ == "__main__":
    sys.exit(main())
