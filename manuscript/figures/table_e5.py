#!/usr/bin/env python3
"""E5 appendix tables (the appraisal inside Gemma 4 31B, exploratory), generated from the run's own records.

    python3 manuscript/figures/table_e5.py      writes table_e5_gate.md, table_e5_swap.md, table_e5_steer.md,
                                                table_e5_heads.md

Sources (read only): data/interp/<E5 run>/summary.json (the run's stored summary) and results.jsonl (per-fixture rows,
for the held-out head patch only). No number is typed by hand; the script checks the values the manuscript quotes
against the stored predictions block. Standard library only.
"""
import json
import os
import re
import statistics as st
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
RUN = "interp-e5-gemma-4-31b-it-20261015T232511Z"
DIR = os.path.join(ROOT, "data", "interp", RUN)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
HEAD = ("<!-- Generated by manuscript/figures/table_e5.py from data/interp/" + RUN + "/summary.json and results.jsonl. "
        "Do not edit by hand. -->\n\n")
CELLS = (("N1", "A0, $100"), ("N6", "A0, $100M"), ("P1", "A1, $100"), ("P6", "A1, $100M"))
# The discovery phase's head sets for prediction E5-5 (scripts/interp_e4_laptop.py TOP8, scripts/interp_e5_laptop.py).
X57 = {(41, 29), (39, 28), (42, 9), (41, 27), (41, 10), (41, 11), (43, 5), (39, 22)}
X61 = {(39, 2), (41, 29), (41, 11), (41, 8), (41, 14), (41, 30), (40, 26), (43, 5)}


def minus(s):
    """Unicode minus for negative numbers only (hyphens in words stay)."""
    return re.sub(r"(?<![\w.])-(?=\d)", "\u2212", s)


def pct(x, signed=True):
    if x is None:
        return "—"
    if round(100 * x) == 0:
        return "0%"
    return minus(f"{100 * x:+.0f}%" if signed else f"{100 * x:.0f}%")


def pts(x):
    return f"{100 * x:.1f}%"


def num(x, n=2):
    return "0." + "0" * n if round(x, n) == 0 else minus(f"{x:+.{n}f}")


def ci(c):
    return "" if not c else f" [{pct(c[0]).rstrip('%')}, {pct(c[1]).rstrip('%')}]"


def load():
    with open(os.path.join(DIR, "summary.json"), encoding="utf-8") as fh:
        s = json.load(fh)
    with open(os.path.join(DIR, "results.jsonl"), encoding="utf-8") as fh:
        rows = [json.loads(l) for l in fh if l.strip()]
    pred = {p["id"]: p for p in s["predictions"]}
    # the values the manuscript quotes, checked against the run's own scoring block
    assert [pred[f"E5-{i}"]["result"] for i in range(1, 7)] == ["HIT"] * 5 + ["MISS"]
    assert pred["E5-1"]["value"] == 0.165 and pred["E5-3"]["value"] == {"reply": 0.572, "S": 0.22}
    assert pred["E5-2"]["value"] == {"max_le_39": 0.005, "max_41_42": 0.835}
    assert pred["E5-5"]["value"]["held_out_share"] == 1.88
    shared = {tuple(x) for x in pred["E5-5"]["value"]["shared"]}
    top = {tuple(x) for x in s["roles"]["seller"]["pick"]["top"]}
    assert shared == top & (X57 | X61) and len(shared) == 6 and len(top & X57) == 4 and len(top & X61) == 5
    return s, rows, pred


def gate_table(s):
    out = ["| Role | Cell | Valid / sampled | Off-scale | Mean gap, transformers | Mean gap, vLLM (Study 3) "
           "| Prompts compared | Per-prompt r |", "|---|---|---|---|---|---|---|---|"]
    for role in ("seller", "buyer"):
        g = s["roles"][role]["gate"]
        assert g["pass"]
        for t, name in CELLS:
            c = g["cells"][t]
            out.append(f"| {role.capitalize()}s | {name} | {c['valid']} / {c['n']} | {c['off_scale']} | {pts(c['mean_gap'])} "
                       f"| {pts(c['vllm_gap'])} | {c['n_prompts']} | {c['r']:.2f} |")
    sh = {r: s["roles"][r]["gate"]["shift"] for r in ("seller", "buyer")}
    b = s["roles"]["buyer"]["gate"]["cells"]["N1"]
    note = ("\nFour sampled openings per prompt with Study 3's response schema; gap = first offer ÷ floor − 1 (sellers) or "
            "1 − first offer ÷ ceiling (buyers). The vLLM column averages Study 3's own openings on the same prompts "
            "(both sessions). $100M − $100 shift, transformers vs vLLM, in points: sellers A0 "
            f"{100 * sh['seller']['A0']['pod']:+.1f} vs {100 * sh['seller']['A0']['vllm']:+.1f}, A1 "
            f"{100 * sh['seller']['A1']['pod']:+.1f} vs {100 * sh['seller']['A1']['vllm']:+.1f}; buyers A0 "
            f"{100 * sh['buyer']['A0']['pod']:+.1f} vs {100 * sh['buyer']['A0']['vllm']:+.1f}, A1 "
            f"{100 * sh['buyer']['A1']['pod']:+.1f} vs {100 * sh['buyer']['A1']['vllm']:+.1f}. The gate required every cell "
            "and shift within 3 points and ≥ 95% valid replies; both roles passed. "
            "Off-scale transformers openings (price outside 0.5–3 times the limit) are not averaged (the vLLM column "
            f"keeps all of Study 3's openings): the {b['off_scale']} buyer "
            "openings at A0 $100 are offers below half the ceiling (for example $50 against a ceiling of $111), so that "
            f"cell compares {b['n_prompts']} of 18 prompts.\n")
    note = minus(note)
    return HEAD + "\n".join(out) + "\n" + note


def swap_table(s):
    layers = [0, 10, 20, 24, 26, 28, 30, 32, 34, 36, 37, 38, 39, 40, 41, 42, 43, 44, 46, 48, 52, 56, 59]
    sw = {r: s["roles"][r]["swap"] for r in ("seller", "buyer")}
    out = ["| Layer | Sellers, adding | Sellers, removing | Buyers, adding | Buyers, removing |", "|---|---|---|---|---|"]
    for L in layers:
        cells = [sw[r][t][f"cure@{L}"]["share"] for r in ("seller", "buyer") for t in ("N6", "P6")]
        out.append(f"| {L} | " + " | ".join(pct(v) for v in cells) + " |")
    for seg, name in (("S", "S tokens only"), ("reply", "reply tokens only")):
        for L in (41, 44, 48, 52):
            cells = [sw[r][t][f"cure {seg}@{L}"]["share"] for r in ("seller", "buyer") for t in ("N6", "P6")]
            out.append(f"| {L}, {name} | " + " | ".join(pct(v) for v in cells) + " |")
    clean = {r: s["roles"][r]["swap_clean"] for r in ("seller", "buyer")}
    note = ("\nShare of the forced opening's log-odds distance between the no-appraisal (A0) and appraisal (A1) runs at "
            "$100M moved by copying the other run's residual-stream states at one layer, on the prompt's last segment "
            "(S: from \"No messages have been sent yet\" to the end of the prompt, including the model-turn header, 68 "
            "tokens) and the reply's 11 "
            "forced opening tokens. Adding: A1 states into the A0 run; removing: A0 states into the A1 run. Readout: "
            "log-odds between the two A0 greedy prices. Ratio of fixture means: sellers "
            f"{s['roles']['seller']['swap']['N6']['cure@41']['n']} floors, buyers "
            f"{s['roles']['buyer']['swap']['N6']['cure@41']['n']} ceilings. Distances (nats): sellers "
            f"{num(clean['seller']['ld']['P6'] - clean['seller']['ld']['N6'])}, buyers "
            f"{num(clean['buyer']['ld']['P6'] - clean['buyer']['ld']['N6'])}. Probability on the two prices' deciding tokens: "
            f"sellers A0 {clean['seller']['pk']['N6']:.2f}, A1 {clean['seller']['pk']['P6']:.2f}; buyers A0 "
            f"{clean['buyer']['pk']['N6']:.2f}, A1 {clean['buyer']['pk']['P6']:.2f}. Both buyer columns are therefore "
            "normalised by a distance measured partly on a run whose openings mostly fall outside the readout.\n")
    return HEAD + "\n".join(out) + "\n" + note


def e54_exact(s):
    """Prediction E5-4's two ratios at full precision (the stored block rounds them to 3 decimals), as evaluate() does."""
    se, key, out = s["roles"]["seller"], "vN@42x1", {}
    stored = {p["id"]: p for p in s["predictions"]}["E5-4"]["value"]
    for p, q in (("P1", "N1"), ("P6", "N6")):
        fa, fb = se["steer_P"][p][key]["per_fixture"], se["steer_N"][q][key]["per_fixture"]
        both = sorted(set(fa) & set(fb))
        r = tuple(st.mean(f_[x][0] for x in both) / st.mean(f_[x][1] for x in both) for f_ in (fa, fb))
        assert (round(r[0], 3), round(r[1], 3), len(both)) == (stored[p]["A1"], stored[p]["A0"], stored[p]["n"])
        out[p] = r
    return out


def steer_table(s):
    out = ["| Role | Openings steered | Vector, layer, α | Points moved | Share of the A0 gap [95% CI] | Valid / n | Off-scale |",
           "|---|---|---|---|---|---|---|"]
    names = {"P1": "A1, $100", "P6": "A1, $100M", "N1": "A0, $100", "N6": "A0, $100M"}
    order = ("vN@42x1", "vN@42x2", "vN@44x1", "vN@44x2", "u@42x1")
    label = {"vN@42x1": "A0 scale direction, L42, 1", "vN@42x2": "A0 scale direction, L42, 2",
             "vN@44x1": "A0 scale direction, L44, 1", "vN@44x2": "A0 scale direction, L44, 2",
             "u@42x1": "non-money control, L42, 1"}
    for role in ("seller", "buyer"):
        r = s["roles"][role]
        for key, targets in (("steer_P", ("P1", "P6")), ("steer_N", ("N1", "N6"))):
            for t in targets:
                for k in order:
                    c = r[key][t][k]
                    out.append(f"| {role.capitalize()}s | {names[t]} | {label[k]} | {c['moved_pts']:+.1f} "
                               f"| {pct(c.get('share'))}{ci(c.get('ci'))} | {c['valid']} / {c['n']} | {c['off_scale']} |"
                               .replace("| -0.0 |", "| 0.0 |").replace("| +0.0 |", "| 0.0 |"))
    out = [minus(r) for r in out]
    e4 = e54_exact(s)
    note = ("\nSampled openings with the no-appraisal scale direction (the ×10⁶ − ×1 difference of A0 states, leave one "
            "fixture out) added on the aligned tokens, toward $100M on $100 prompts and toward $100 on $100M prompts; "
            "share = mean opening change over the mean A0 vLLM gap between scales of the same fixtures. A1 rows use all "
            "fixtures (sellers 19, buyers 18); A0 rows use the 7 discovery floors or ceilings. Prediction E5-4 compares "
            f"the 7 discovery floors only: A1 {pct(e4['P1'][0], False)} and {pct(e4['P6'][0], False)} against A0 "
            f"{pct(e4['P1'][1], False)} and {pct(e4['P6'][1], False)} (×1 + v and ×10⁶ − v).\n")
    return HEAD + "\n".join(out) + "\n" + note


def heads_table(s, rows):
    se = s["roles"]["seller"]
    pick = se["pick"]
    top = [tuple(x) for x in pick["top"]]
    out = ["| Head (layer.head) | Score (discovery floors) | In the scale set (X57) | In the range set (X61) |",
           "|---|---|---|---|"]
    for L, h in top:
        out.append(f"| {L}.{h} | {pick['scores'][f'h{L}.{h}']:.3f} | {'yes' if (L, h) in X57 else '—'} "
                   f"| {'yes' if (L, h) in X61 else '—'} |")
    # held-out circuit (A1 states of the 8 heads into the A0 x1e6 run), per fixture, from results.jsonl
    per, other = [], {}
    for r in rows:
        if r.get("step") != "e5 seller swap circuit":
            continue
        T = r["targets"]
        row = {x["n"]: x["ld"] for x in T["N6"]["rows"]}
        per.append((r["fixture"], row["top8"] - T["N6"]["ld_clean"], T["P6"]["ld_clean"] - T["N6"]["ld_clean"],
                    r["ld_build"]["N6"] - r["ld_build"]["N1"], row["random8"] - T["N6"]["ld_clean"]))
        for k in ("top1", "top4", "top8 S", "top8 reply", "random8"):
            other.setdefault(k, []).append(row[k] - T["N6"]["ld_clean"])
    assert len(per) == len(se["held_out"]) == 12
    moved, den, gap, rnd = (st.mean(p[i] for p in per) for i in (1, 2, 3, 4))
    K = se["circuit"]["N6"]
    assert abs(K["top8"]["moved"] - moved) < 1e-9 and abs(K["top8"]["gap"] - den) < 1e-9
    att = se["attention"]["top_last_to_hi"]
    note = ("\nThe appraisal swap at single heads (layers 38–44, 224 heads) on the 7 discovery floors; score = mean share of "
            "both directions. Six of these eight heads are in the union of the discovery phase's two top-eight sets "
            "(13 heads; expected overlap by chance 8 × 13 / 224 ≈ 0.46): four in the scale set, five in the range set. "
            "Last-token attention to the appraisal's digits, highest heads: "
            + "; ".join(("at $100 " if k == "P1" else "at $100M ") + ", ".join(f"{L}.{h} ({m:.2f})" for L, h, m in v[:4])
                        for k, v in att.items()) + ". "
            f"Held-out floors (12): patching the eight heads' outputs from the A1 run into the A0 $100M run moves the "
            f"log-odds by {num(moved)} nats on average (negative, toward the $100 price, on {sum(p[1] < 0 for p in per)} "
            f"of 12 floors), {abs(moved) / gap:.0%} of these floors' own A0 scale gap ({num(gap)} nats); eight random "
            f"heads move {num(rnd)}. The registered share divides by the A1 − A0 distance at $100M on the A0-price "
            f"readout, which ranges from {num(min(p[2] for p in per), 1)} to {num(max(p[2] for p in per), 1)} nats across "
            f"floors (mean {num(den)}), so its ratio ({K['top8']['share']:.2f}, 95% CI {pct(K['top8']['ci'][0])} to "
            f"{pct(K['top8']['ci'][1])}) is not interpretable. Other held-out rows, as shares of the floors' own A0 gap: "
            + ", ".join(f"{name} {pct(-st.mean(other[k]) / gap, False)}" for k, name in
                        (("top1", "top head"), ("top4", "top 4"), ("top8 S", "top 8 on S only"),
                         ("top8 reply", "top 8 on reply only"), ("random8", "random 8")))
            + f" (as ratios to the registered denominator: {pct(K['top1']['share'])}, {pct(K['top4']['share'])}, "
            f"{pct(K['top8 S']['share'])}, {pct(K['top8 reply']['share'])} and {pct(K['random8']['share'])}).\n")
    note = minus(note)
    return HEAD + "\n".join(out) + "\n" + note


def patch_table(s):
    """The seller patch rows (E4's instrument on Study 3's prompts), share of the A0 scale gap, all four prompts."""
    P = s["roles"]["seller"]["patch"]
    names = []
    for t in ("N1", "N6", "P1", "P6"):
        names += [n for n in P[t] if n not in names]
    label = {"own": "other scale's states, same condition", "plain": "A0 scale difference added",
             "vN": "A0 scale direction, α 1", "vNx2": "A0 scale direction, α 2", "u": "non-money control, α 1",
             "rand": "random direction, α 1", "top8 set": "8 heads: other scale's outputs",
             "top8 add": "8 heads: A0 scale difference added", "rand8 add": "8 random heads: A0 difference added",
             "top8 add reply": "8 heads, reply tokens only: A0 difference added",
             "rand8 set": "8 random heads: other scale's outputs"}

    def name(n):
        if "@" in n:
            kind, L = n.split("@")
            tok = ", reply tokens only" if kind.endswith(" reply") else ""
            return f"{label[kind.replace(' reply', '')]}{tok}, L{L}"
        return label[n]
    out = ["| Patch | A0, $100 | A0, $100M | A1, $100 | A1, $100M |", "|---|---|---|---|---|"]
    for n in names:
        out.append(f"| {name(n)} | " + " | ".join(
            (pct(P[t][n]["share"]) + ci(P[t][n].get("ci"))) if n in P[t] else "—" for t in ("N1", "N6", "P1", "P6")) + " |")
    pc = s["roles"]["seller"]["patch_clean"]
    note = ("\nSellers, 19 floors, forced opening; each row moves the target run toward the other scale and is reported as "
            "a share of the A0 log-odds gap between scales of the same floors (G_N = "
            f"{num(pc['G_N'])} nats; under A1 the gap is {num(pc['G_P'])} nats, {pct(pc['G_P_share'], False)} of G_N), "
            "95% bootstrap CI over floors. Patches act on the aligned tokens (the prompt after the limit and the reply's "
            "11 opening tokens) unless marked. \"A0 scale difference added\" (A1 prompts only) adds the A0 run's "
            "other-scale-minus-this-scale states to the A1 run. The eight heads are the discovery phase's scale heads "
            "(X57); directions are leave-one-floor-out.\n")
    return HEAD + "\n".join(minus(r) for r in out) + "\n" + minus(note)


def circuit_table(s, rows):
    """Held-out floors, per floor: the eight appraisal heads' A1 outputs patched into the A0 $100M run."""
    se = s["roles"]["seller"]
    out = ["| Floor | Floor at $100 | Moved by the 8 heads (nats) | Own A0 scale gap (nats) | Share of own gap "
           "| Registered denominator: A1 − A0 at $100M (nats) | Moved by 8 random heads (nats) |",
           "|---|---|---|---|---|---|---|"]
    per = []
    for r in rows:
        if r.get("step") != "e5 seller swap circuit":
            continue
        T = r["targets"]
        row = {x["n"]: x["ld"] for x in T["N6"]["rows"]}
        moved, gap = row["top8"] - T["N6"]["ld_clean"], r["ld_build"]["N6"] - r["ld_build"]["N1"]
        den, rnd = T["P6"]["ld_clean"] - T["N6"]["ld_clean"], row["random8"] - T["N6"]["ld_clean"]
        per.append((moved, gap, den, rnd))
        out.append(f"| {r['fixture']} | ${r['base_limit']} | {num(moved)} | {num(gap)} | {pct(-moved / gap, False)} "
                   f"| {num(den)} | {num(rnd)} |")
    assert sorted(r_["fixture"] for r_ in rows if r_.get("step") == "e5 seller swap circuit") == sorted(se["held_out"])
    m = [st.mean(p[i] for p in per) for i in range(4)]
    out.append(f"| **Mean** | | **{num(m[0])}** | **{num(m[1])}** | **{pct(-m[0] / m[1], False)}** | **{num(m[2])}** "
               f"| **{num(m[3])}** |")
    note = ("\nNegative moves are toward the $100 price. The registered E5-5 share is the mean move over the mean "
            "registered denominator; because that denominator changes sign across floors, the ratio "
            f"({se['circuit']['N6']['top8']['share']:.2f}) does not measure a share. The own-gap column, computed after "
            "the run, is the direct effect reported in Section 6.\n")
    return HEAD + "\n".join(minus(r) for r in out) + "\n" + minus(note)


def main():
    s, rows, _ = load()
    for stem, text in (("table_e5_gate", gate_table(s)), ("table_e5_swap", swap_table(s)),
                       ("table_e5_steer", steer_table(s)), ("table_e5_patch", patch_table(s)),
                       ("table_e5_heads", heads_table(s, rows)), ("table_e5_circuit", circuit_table(s, rows))):
        path = os.path.join(HERE, stem + ".md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print("wrote", path)


if __name__ == "__main__":
    main()
