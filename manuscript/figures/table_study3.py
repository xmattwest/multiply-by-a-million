#!/usr/bin/env python3
"""Study 3 tables for the manuscript, generated from derived/study3/study3.json (the registered analysis, run once).

    python3 manuscript/figures/table_study3.py      writes table_s3_primary.md, table_s3_secondary_a.md,
                                                    table_s3_secondary_b.md, table_s3_secondary_c.md, and the
                                                    appendix tables
                                                    table_s3_arms.md (from the six session manifests),
                                                    table_s3_clamp.md (from prereg/study3/clamp_values.json) and
                                                    table_s3_quality.md (study3.json quality_by_cell)

No number in these tables is typed by hand. Standard library only.
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, "derived", "study3", "study3.json")
ORDER = [("gemma-4-31b-it", "Gemma 4 31B"), ("qwen3.8-27b-fp8", "Qwen3.8 27B"), ("gpt-6-luna", "gpt-6-luna"),
         ("claude-haiku-5.5", "claude-haiku-5.5"), ("gemini-3.5-flash-lite", "gemini-3.5-flash-lite")]
A0_SHIFT = {"gemma-4-31b-it", "gpt-6-luna", "gemini-3.5-flash-lite"}     # §5.1 P2 A0 predictions
HEAD = ("<!-- Generated by manuscript/figures/table_study3.py from derived/study3/study3.json. "
        "Do not edit by hand. -->\n\n")


def head(src):
    return f"<!-- Generated by manuscript/figures/table_study3.py from {src}. Do not edit by hand. -->\n\n"


def f(x, n=3):
    return f"{x:+.{n}f}".replace("-", "−")


def ci(c):
    return f"[{f(c[0])}, {f(c[1])}]" if c else "—"


def p(x):
    return "< 0.001" if x < 0.001 else f"{x:.3f}"


def mark(ok):
    return "✓" if ok else "✗"


def primary(d):
    rows = ["| Model | P1 · I > 0 | P2 · A0 shift or equivalence | P2 · A1 equivalence | P3a · κ ≈ 0 | P3b · ω − Δm ≈ 0 |",
            "|---|---|---|---|---|---|"]
    met = [0] * 5
    for m, name in ORDER:
        v = d["per_model"][m]
        p1, a0, a1 = v["P1"], v["P2"]["A0"], v["P2"]["A1"]
        k, b = v["P3"]["P3a_kappa"], v["P3"]["P3b_omega_minus_delta_m"]
        hit = [p1["supported"],
               a0["p_holm_across_models"] < 0.05 if m in A0_SHIFT else a0["H2_equivalent_within_0.10"],
               a1["H2_equivalent_within_0.10"], k["equivalent_within_0.05"], b["equivalent_within_0.05"]]
        met = [x + y for x, y in zip(met, hit)]
        rows.append(
            f"| {name} | {mark(hit[0])} {f(p1['mean'])} {ci(p1['ci90'])}; p {p(p1['p_holm_across_models'])} "
            f"| {mark(hit[1])} {f(a0['mean'])} {ci(a0['ci90'])}; p {p(a0['p_holm_across_models'])}"
            f"{'' if a0['H2_equivalent_within_0.10'] else '; not equiv.'} "
            f"| {mark(hit[2])} {f(a1['mean'])} {ci(a1['ci90'])}; p {p(a1['p_holm_across_models'])} "
            f"| {mark(hit[3])} {f(k['mean'])} {ci(k['ci90'])}; p {p(k['p_holm_across_models'])} "
            f"| {mark(hit[4])} {f(b['mean'])} {ci(b['ci90'])} |")
    rows.append("| **Predictions met** | " + " | ".join(f"**{x} of 5**" for x in met) + " |")
    note = ("\nMean over 40 fixtures [90% bootstrap CI]; p: Wilcoxon signed-rank (200,000 sign flips), Holm across the "
            "five models (P1 one-sided). Predictions (registration §5.1): P1 I > 0 on all five; P2 A0 a shift on Gemma, Luna and "
            "Gemini (two-sided test) and equivalence within ±0.10 on Qwen and Haiku; P2 A1 equivalence within ±0.10 "
            "on all five; P3a κ and P3b ω − Δm equivalent to zero within ±0.05 (90% CI). A non-significant test is "
            f"never read as equivalence. Total: {sum(met)} of 25.\n")
    return HEAD + "\n".join(rows) + "\n" + note


def secondary_a(d):
    rows = ["| Model | S1 h(A0) | S1 h(A1), ±0.03 | S2 $100K − $100 (A0 / A1) | S2 $100M − $100K (A0 / A1) "
            "| S3 seller utility (A0) | S4 HB, A0 / A1 |", "|---|---|---|---|---|---|---|"]
    for m, name in ORDER:
        s = d["per_model"][m]["secondary"]
        w = s["S2_S3_within_model_family"]
        h0, h1 = s["S1_HA_A0"], s["S1_h_A1_equivalence"]
        def two(a, b):
            return f"{f(w[a]['mean'])} (p {p(w[a]['p_holm_within_model'])}) / {f(w[b]['mean'])} (p {p(w[b]['p_holm_within_model'])})"
        rows.append(
            f"| {name} | {f(h0['mean'])} {ci(h0['ci95'])}; p {p(h0['p_holm_across_models'])} "
            f"| {f(h1['mean'])} {ci(h1['ci90'])}; {'equiv.' if h1['equivalent_within_0.03'] else 'not equiv.'} "
            f"| {two('S2a_100K_vs_100_A0', 'S2a_100K_vs_100_A1')} | {two('S2b_100M_vs_100K_A0', 'S2b_100M_vs_100K_A1')} "
            f"| {f(w['S3_seller_utility_A0']['mean'])} (p {p(w['S3_seller_utility_A0']['p_holm_within_model'])}) "
            f"| {f(s['S4_HB_A0']['mean_I'])} (p {p(s['S4_HB_A0']['p_holm_across_models'])}) / "
            f"{f(s['S4_HB_A1']['mean_I'])} (p {p(s['S4_HB_A1']['p_holm_across_models'])}) |")
    note = ("\nS1: change in the opener's first-offer gap from its own limit, $100M − $100 [95% CI; S1 A1 90% CI]; HA "
            "predicts h(A0) < 0 (one-sided, Holm across models). S2: closing shift between adjacent scales, Holm within "
            "model. S3: all-game seller utility (failed deals 0, forfeits −1), $100M − $100. S4: opener's advantage in "
            "seller share at $100M minus at $100 (two-sided, Holm across models). The other S3 contrasts (agreement "
            "rate, coarse prices, and seller utility under A1) are in the table of remaining S3, S8 and S9 results.\n")
    return HEAD + "\n".join(rows) + "\n" + note


def secondary_b(d):
    rows = ["| Model | S5 calibration HM1, ±0.05 | S5 tracking HM2 ρ | S6 artefact $100 / $100M | S8 A0 vs earlier "
            "| S9 ρ, A1 at $100 / $100M |", "|---|---|---|---|---|---|"]
    flagged = []
    for m, name in ORDER:
        s = d["per_model"][m]["secondary"]
        h1, h2 = s["S5_HM_A0"]["HM1"], s["S5_HM_A0"]["HM2"]
        s6a, s6b = s["S6_scripting_artefact_x1e2"], s["S6_scripting_artefact_x1e8"]
        s8 = s["S8_consistency_with_earlier_descriptive"]["A0"]
        s9 = s["S9_appraisal_position_moderator"]
        rows.append(
            f"| {name} | {f(h1['mean'])} {ci(h1['ci90'])}; {'equiv.' if h1['equivalent_within_0.05'] else 'not equiv.'} "
            f"| {h2['spearman']:.2f} (p {p(h2.get('p_holm_across_models', h2['p_one_sided_unadjusted']))}) "
            f"| {f(s6a['mean'])} (p {p(s6a['p_two_sided_unadjusted'])}) / {f(s6b['mean'])} (p {p(s6b['p_two_sided_unadjusted'])}) "
            f"| {f(s8['earlier_mean_d'])} → {f(d['per_model'][m]['P2']['A0']['mean'])}, diff {ci(s8['ci95'])} "
            f"| {s9['position_vs_share_A1_x1e2']['spearman']:.2f} / {s9['position_vs_share_A1_x1e8']['spearman']:.2f} |")
        for key, x in s["S7_session_consistency"].items():
            if isinstance(x, dict) and "paired_difference" in x:
                lo, hi = x["paired_difference"]["ci95"]
                if lo > 0 or hi < 0:
                    flagged.append(f"{name} {key} ({f(x['session1_mean'])} → {f(x['session2_mean'])})")
    note = ("\nS5: in the natural A0 games, deal position minus the first offers' midpoint (calibration, 90% CI) and the "
            "Spearman correlation of their scale shifts across fixtures (tracking, 20,000 permutations). S6: diagonal "
            "clamp cells minus natural A0 games at the same scale. S8: A0 closing shift in Study 2 (Qwen, Gemma) or "
            "Addendum C (API) against Study 3, unpaired fixture bootstrap, 95% CI. S9: Spearman correlation across "
            "fixtures between the appraisal's position in the zone and seller share under A1 (exploratory-labelled "
            "moderator). S7, primary statistics whose session-1 vs session-2 paired 95% CI excludes zero: "
            + ("; ".join(flagged) if flagged else "none") + ".\n")
    return HEAD + "\n".join(rows) + "\n" + note


def secondary_c(d):
    """The registered secondaries not shown in secondary_a/b: S3 agreement rate and coarse prices (A0 and A1),
    S3 seller utility under A1, S8's A1 comparison with Study 1 (Qwen only) and S9's moderation of the A1 shift."""
    rows = ["| Model | S3 agreement rate (A0 / A1) | S3 coarse-grid price (A0 / A1) | S3 seller utility (A1) "
            "| S8 A1 vs Study 1 | S9 ρ, position vs A1 shift |", "|---|---|---|---|---|---|"]
    for m, name in ORDER:
        s = d["per_model"][m]["secondary"]
        w = s["S2_S3_within_model_family"]
        def two(a, b):
            return f"{f(w[a]['mean'])} (p {p(w[a]['p_holm_within_model'])}) / {f(w[b]['mean'])} (p {p(w[b]['p_holm_within_model'])})"
        s8 = s["S8_consistency_with_earlier_descriptive"].get("A1_vs_study1_appraisal_and_ranges")
        assert (s8 is not None) == (m == "qwen3.8-27b-fp8"), m
        s8txt = (f"{f(s8['earlier_mean_d'])} → {f(d['per_model'][m]['P2']['A1']['mean'])}; diff {f(s8['diff'])} {ci(s8['ci95'])}"
                 if s8 else "—")
        rho = s["S9_appraisal_position_moderator"]["position_vs_d_A1_spearman"]
        rows.append(
            f"| {name} | {two('S3_agreement_rate_A0', 'S3_agreement_rate_A1')} "
            f"| {two('S3_coarse_price_A0', 'S3_coarse_price_A1')} "
            f"| {f(w['S3_seller_utility_A1']['mean'])} (p {p(w['S3_seller_utility_A1']['p_holm_within_model'])}) "
            f"| {s8txt} | {f(rho, 2)} |")
    note = ("\nAll contrasts are $100M − $100 fixture means. S3 agreement rate: share of games that end in a deal; "
            "coarse-grid price: seller share with the $100M price rounded to whole millions (the $100 game's grid); seller utility: all "
            "games, failed deals 0 and forfeits −1. S3 p-values are two-sided Wilcoxon, Holm within model over the ten "
            "S2 and S3 contrasts. S8: Qwen's A1 closing shift against Study 1, which showed the appraisal together with "
            "both limit ranges (unpaired fixture bootstrap, 95% CI; descriptive, with that caveat); the other models did "
            "not run Study 1. S9: Spearman correlation across fixtures between the appraisal's position in the zone, "
            "(V − F)/(C − F), and the A1 closing shift; the registered analysis computes no p-value for it.\n")
    return HEAD + "\n".join(rows) + "\n" + note


def arms(d):
    """Model arms and settings as the six session manifests record them (both sessions must agree)."""
    seen = {}
    for run in d["runs"]:
        m = json.load(open(os.path.join(ROOT, "data", "runs", run, "run_manifest.json"), encoding="utf-8"))
        for arm, a in m["arms"].items():
            row = (m["backend"], m["concurrency"], m["max_tokens"], json.dumps(a, sort_keys=True))
            assert seen.setdefault(arm, row) == row, (arm, run)
            assert m["max_messages"] == 16 and m["max_message_chars"] == 500
    rows = ["| Model | Backend | Weights or returned version | Sampling | Thinking | Seed sent | Concurrent games |",
            "|---|---|---|---|---|---|---|"]
    for arm, name in ORDER:
        backend, conc, max_tokens, a = seen[arm][0], seen[arm][1], seen[arm][2], json.loads(seen[arm][3])
        assert max_tokens == 1024
        if backend == "vllm":
            s = a["sampling"]
            assert a["presence_penalty"] == a["frequency_penalty"] == 0 and a["repetition_penalty"] == 1.0
            rows.append(f"| {name} | vLLM 0.30.0 | `{a['repo']}` @ `{a['revision'][:7]}` | temperature {s['temperature']:.1f}, "
                        f"top-p {s['top_p']:g}, top-k {s['top_k']} | off | yes | {conc} |")
        else:
            think = {"none": "effort \"none\"", "minimal": "effort \"minimal\""}.get(
                a["reasoning"].get("effort"), "disabled" if a["reasoning"].get("enabled") is False else "?")
            rows.append(f"| {name} | OpenRouter, {a['vendor']} only | `{a['canonical']}` | vendor defaults | {think} "
                        f"| {'yes' if a['send_seed'] else 'no'} | {conc} |")
    note = ("\nFrom the `arms` block of the six session manifests (identical in both sessions of each model). Every arm: "
            "at most 16 messages, 500 characters per message, 1,024 output tokens per reply. Open-weight arms: presence "
            "and frequency penalties 0, repetition penalty 1, image pinned by digest. API arms: the vendor's own endpoint "
            "only, no fallbacks; no temperature, top-p or top-k is sent.\n")
    return head("the six Study 3 session manifests (data/runs/s3-*/run_manifest.json)") + "\n".join(rows) + "\n" + note


def clamp(d):
    """The frozen scripted first-offer positions (zone units) and their scripted midpoints."""
    c = json.load(open(os.path.join(ROOT, "prereg", "study3", "clamp_values.json"), encoding="utf-8"))
    rows = ["| Model | Opener | Source scale | Seller's position | Buyer's position | Scripted midpoint | Earlier games |",
            "|---|---|---|---|---|---|---|"]
    for arm, name in ORDER:
        for opener in ("seller", "buyer"):
            for sc, label in (("x1e2", "$100"), ("x1e8", "$100M")):
                v = c["values"][arm][opener][sc]
                xs, xb = float(v["x_seller"]), float(v["x_buyer"])
                n = c["detail_not_used_for_pricing"][arm][opener][sc]["n_games"]
                rows.append(f"| {name} | {opener} | {label} | {f(xs, 4)} | {f(xb, 4)} | {f((xs + xb) / 2, 4)} | {n} |")
    note = ("\nFrom `prereg/study3/clamp_values.json` (hashed in the registration): means of each model's earlier "
            "no-appraisal games containing both first offers (Study 2 for Qwen and Gemma, Addendum C for the API "
            "models), in zone units x = (P − F)/(C − F). Scripted price = F + x(C − F), rounded half up to a multiple of "
            "V/100, so the $100M prices are the $100 prices with six zeros appended. Positions outside [0, 1] are "
            "first offers outside the zone, scripted as the models played them; P3b uses only the change Δm between "
            "source scales.\n")
    return head("prereg/study3/clamp_values.json") + "\n".join(rows) + "\n" + note


def quality(d):
    rows = ["| Model | Games | Agreements | Walkaways | No deal by message 16 | Forfeits | Agreements outside the zone "
            "| Trailing text ignored (replies) | Mean messages |", "|---|---|---|---|---|---|---|---|---|"]
    for arm, name in ORDER:
        v = d["per_model"][arm]
        assert v["games_scored"] == 3200 and not v["games_missing"] and not v["flags"]
        t, n, oz, tt, msg = {}, 0, 0, 0, 0.0
        for q in v["quality_by_cell"].values():
            for k, x in q["terminals"].items():
                t[k] = t.get(k, 0) + x
            n += q["games"]
            oz += q["outside_zopa"]
            tt += q["trailing_text_calls"]
            msg += q["mean_messages"] * q["games"]
            assert q["reasoning_token_calls"] == q["reasoning_text_calls"] == q["refusals"] == 0
        assert n == 3200 and sum(t.values()) == n
        rows.append(f"| {name} | {n:,} | {t.get('AGREEMENT', 0):,} | {t.get('WALKAWAY', 0)} | {t.get('TIMEOUT', 0)} "
                    f"| {t.get('PROTOCOL_FORFEIT', 0)} | {oz} | {tt} | {msg / n:.1f} |")
    note = ("\nAll ten cells, both sessions. No model had a refusal, a reasoning token or reasoning text (Gemini at its "
            "lowest setting included), and no registered quality flag (more than 25% forfeits, or more than 10 points "
            "between extreme scales) was raised. Agreements outside the zone are retained and scored unclipped, as "
            "registered.\n")
    return HEAD + "\n".join(rows) + "\n" + note


def main():
    d = json.load(open(SRC, encoding="utf-8"))
    assert d["registered"] and len(d["holm_family"]) == 5
    for stem, fn in (("table_s3_primary", primary), ("table_s3_secondary_a", secondary_a),
                     ("table_s3_secondary_b", secondary_b), ("table_s3_secondary_c", secondary_c), ("table_s3_arms", arms), ("table_s3_clamp", clamp),
                     ("table_s3_quality", quality)):
        path = os.path.join(HERE, stem + ".md")
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(fn(d))
        print("wrote", path)


if __name__ == "__main__":
    main()
