def tex_num(x, n=3, signed=True):
    s = f"{x:+.{n}f}" if signed else f"{x:.{n}f}"
    if s.startswith("-"):
        return f"$-${s[1:]}"
    if signed and s.startswith("+"):
        return f"$+${s[1:]}"
    return s


def tex_ci(c, n=3):
    if not c:
        return "---"
    return f"[{tex_num(c[0], n)}, {tex_num(c[1], n)}]"


def tex_p(x):
    if x < 0.001:
        return "$< 0.001$"
    return f"${x:.3f}$"


def tex_pct(x, signed=True):
    if x is None:
        return "---"
    if round(100 * x) == 0:
        return "0\\%"
    if signed:
        s = f"{100 * x:+.0f}"
        if s.startswith("-"):
            return f"$-${s[1:]}\\%"
        return f"$+${s[1:]}\\%"
    return f"{100 * x:.0f}\\%"


def tex_pts(x):
    return f"{100 * x:.1f}\\%"


def tex_mark(ok):
    return r"\cmark" if ok else r"\xmark"


def tex_escape(s):
    return (s.replace("\\", r"\textbackslash{}")
             .replace("_", r"\_")
             .replace("%", r"\%")
             .replace("&", r"\&")
             .replace("#", r"\#")
             .replace("$", r"\$"))


def mc(line1, line2):
    return f"\\makecell{{{line1} \\\\{{}} {line2}}}"


