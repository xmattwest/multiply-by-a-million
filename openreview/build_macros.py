    for r in rows:
        if r[0] == "Mean":
            lines.append(r"\midrule")
            lines.append(" & ".join(f"\\textbf{{{c}}}" if c else "" for c in r) + r" \\")
        else:
            lines.append(" & ".join(r) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", r"\end{table}", ""])
    return "\n".join(lines)


